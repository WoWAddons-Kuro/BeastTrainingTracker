ns.rarePets, ns.rarePetByName = {}, {}
for _, r in ipairs(P) do
  local fl = r[6] or ""
  local p = {
    name = r[1], family = r[2], level = r[3], zone = r[4], speed = r[5],
    rare = fl:find("R", 1, true) ~= nil,
    elite = fl:find("E", 1, true) ~= nil,
    spawned = fl:find("S", 1, true) ~= nil,
    unique = fl:find("U", 1, true) ~= nil,
    minLevel = tonumber(r[3]:match("^(%d+)")) or 0,
    dungeon = r[4]:find("(Dungeon)", 1, true) ~= nil or r[4]:find("(Raid)", 1, true) ~= nil,
  }
  ns.rarePets[#ns.rarePets + 1] = p
  ns.rarePetByName[p.name] = p
end
